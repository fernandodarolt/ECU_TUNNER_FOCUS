'use strict';

const test = require('node:test');
const assert = require('node:assert/strict');
const { createHash } = require('node:crypto');
const core = require('../src/core.js');
const { baseSynthetic } = require('./synthetic.cjs');

test('synthetic fixture satisfies all three independent checksum contracts', () => {
  const { bytes } = baseSynthetic();
  const status = core.checkImage(bytes);
  assert.equal(status.principal.valid, true);
  assert.equal(status.boot.valid, true);
  assert.equal(status.vid.valid, true);
  assert.equal(status.ok, true);
});

test('numbers accept decimal comma and exponents but reject nonfinite and partial input', () => {
  assert.equal(core.parseNumber('  -1,25  '), -1.25);
  assert.equal(core.parseNumber('2.5e2'), 250);
  assert.equal(core.parseNumber('.125'), 0.125);
  for (const bad of ['', '12oops', '1,2,3', 'Infinity', 'NaN', '1e999', Infinity, NaN]) {
    assert.throws(() => core.parseNumber(bad));
  }
});

test('rectangular paste parsing accepts localized decimals and rejects ragged rows', () => {
  assert.deepEqual(core.parseBlock('1,5;2\n3;4,5'), [[1.5, 2], [3, 4.5]]);
  assert.deepEqual(core.parseBlock('1\t2\n3\t4'), [[1, 2], [3, 4]]);
  assert.throws(() => core.parseBlock('1 2\n3'));
  assert.throws(() => core.parseBlock(''));
  assert.deepEqual(core.rectIndices(3, 1, 2, 0, 1), [1, 2, 4, 5]);
});

test('SHA256 agrees with the platform implementation on generated bytes', () => {
  const bytes = Uint8Array.from({ length: 257 }, (_, i) => (i * 31) & 255);
  assert.equal(core.sha256(bytes), createHash('sha256').update(bytes).digest('hex'));
  assert.equal(core.sha256(new Uint8Array()), 'e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855');
});

test('editing a rectangle stores float32 big endian values and leaves the input untouched', () => {
  const { bytes, profile, mapId } = baseSynthetic();
  const editor = new core.Editor(profile, bytes, 'synthetic-input');
  editor.apply(mapId, core.rectIndices(3, 0, 1, 1, 2), 'add', '0,5');
  assert.deepEqual(Array.from({ length: 6 }, (_, i) => editor.value(mapId, i)), [1, 2.5, 3.5, 4, 5.5, 6.5]);
  assert.deepEqual(Array.from(editor.bytes().slice(0x140104, 0x140108)), [0x40, 0x20, 0, 0]);
  assert.equal(new DataView(bytes.buffer).getFloat32(0x140104, false), 2);
  assert.deepEqual(editor.mapStats(mapId), { min: 1, max: 6.5, changed: 4, cells: 6 });
  assert.equal(editor.checksums().principal.valid, false);
});

test('undo and redo restore whole transactions and a new edit clears redo', () => {
  const { bytes, profile, mapId } = baseSynthetic();
  const editor = new core.Editor(profile, bytes, 'synthetic-input');
  editor.paste(mapId, 1, '10\t20\n30\t40');
  assert.equal(editor.history.length, 1);
  assert.equal(editor.undo(), true);
  assert.deepEqual(editor.bytes(), bytes);
  assert.equal(editor.redo(), true);
  assert.equal(editor.value(mapId, 5), 40);
  editor.undo();
  editor.setCells(mapId, [{ index: 0, value: 8 }]);
  assert.equal(editor.canRedo, false);
  assert.equal(editor.redo(), false);
});

test('invalid paste and overflowing float writes are atomic', () => {
  const { bytes, profile, mapId } = baseSynthetic();
  const editor = new core.Editor(profile, bytes, 'synthetic-input');
  assert.throws(() => editor.paste(mapId, 2, '1 2'));
  assert.throws(() => editor.setCells(mapId, [{ index: 0, value: 9 }, { index: 1, value: 1e100 }]));
  assert.throws(() => editor.setCells(mapId, [{ index: 6, value: 0 }]));
  assert.deepEqual(editor.bytes(), bytes);
  assert.equal(editor.canUndo, false);
});

test('in-memory binary export repairs principal checksum without changing boot or VID', () => {
  const { bytes, profile, mapId } = baseSynthetic();
  const editor = new core.Editor(profile, bytes, 'synthetic-input');
  editor.apply(mapId, [0, 1], 'multiply', 2);
  const exported = editor.exportBIN();
  assert.equal(exported.checksums.ok, true);
  assert.equal(exported.checksums.principal.actual, 1);
  assert.equal(exported.sha256, createHash('sha256').update(exported.bytes).digest('hex'));
  assert.deepEqual(exported.bytes.slice(0x100C0, 0x10140), bytes.slice(0x100C0, 0x10140));
  assert.deepEqual(exported.bytes.slice(0x10238, 0x10278), bytes.slice(0x10238, 0x10278));
  const allowed = new Set(profile.maps[0].addresses.flatMap(a => [a, a + 1, a + 2, a + 3]));
  for (let a = 0x15BD8C; a < 0x15BD90; a++) allowed.add(a);
  for (const change of editor.changes()) assert.equal(allowed.has(change.address), true);
  assert.equal(core.checkImage(bytes).ok, true);
});

test('principal, boot and VID corruption are reported independently', () => {
  for (const [address, failed] of [[0x140118, 'principal'], [0x10238, 'boot'], [0x100C2, 'vid']]) {
    const { bytes } = baseSynthetic();
    bytes[address] ^= 1;
    const status = core.checkImage(bytes);
    assert.equal(status.ok, false);
    for (const part of ['principal', 'boot', 'vid']) assert.equal(status[part].valid, part !== failed);
  }
});

test('export refuses invalid boot and VID instead of repairing them', () => {
  for (const address of [0x10238, 0x100C2]) {
    const { bytes, profile } = baseSynthetic();
    bytes[address] ^= 1;
    const editor = new core.Editor(profile, bytes, 'synthetic-corrupt-input');
    assert.throws(() => editor.exportBIN(), /boot ou VID/);
    assert.deepEqual(editor.bytes(), bytes);
  }
});

test('project roundtrip preserves edits and the synthetic source entirely in memory', () => {
  const { bytes, profile, mapId } = baseSynthetic();
  const editor = new core.Editor(profile, bytes, 'synthetic-input');
  editor.paste(mapId, 0, '0,25;0,5\n0,75;1');
  const projectText = editor.project();
  const restored = core.Editor.fromProject(profile, projectText);
  assert.deepEqual(restored.bytes(), editor.bytes());
  assert.equal(restored.filename, 'synthetic-input');
  assert.equal(restored.comparisonMode, false);
  assert.equal(restored.value(mapId, 0, 'base'), 1);
  assert.equal(restored.value(mapId, 0), 0.25);
  assert.deepEqual(restored.loaded, bytes);
  assert.equal(restored.exportBIN().checksums.ok, true);
});

test('comparison separates preexisting differences from session edits and survives project roundtrip', () => {
  const { bytes, profile, mapId } = baseSynthetic();
  const source = new core.Editor(profile, bytes, 'synthetic-source');
  source.setCells(mapId, [{ index: 0, value: 7 }]);
  const modified = source.exportBIN().bytes;
  modified[0x5000] = 0xA5; // Invented noneditable difference outside code and guards.
  const compared = core.Editor.compare(profile, bytes, modified, 'synthetic-reference', 'synthetic-modified');
  assert.equal(compared.value(mapId, 0, 'base'), 1);
  assert.equal(compared.value(mapId, 0), 7);
  assert.equal(compared.sourceChanges().length, 0);
  const summary = compared.comparisonSummary();
  assert.ok(summary.editableBytes > 0);
  assert.equal(summary.outsideEditableBytes, 1);
  assert.equal(summary.totalBytes, summary.editableBytes + 1);
  compared.setCells(mapId, [{ index: 5, value: 12 }]);
  assert.ok(compared.sourceChanges().length > 0);
  const restored = core.Editor.fromProject(profile, compared.project());
  assert.equal(restored.comparisonMode, true);
  assert.equal(restored.referenceFilename, 'synthetic-reference');
  assert.deepEqual(restored.bytes(), compared.bytes());
  assert.deepEqual(restored.base, bytes);
  assert.deepEqual(restored.loaded, modified);
  assert.deepEqual(restored.comparisonSummary(), compared.comparisonSummary());
});

test('wrong marker, guard, code hash, image size and nonfinite map values are rejected', () => {
  for (const address of [0x4000, 0x4100, 0x4200]) {
    const { bytes, profile } = baseSynthetic();
    bytes[address] ^= 1;
    assert.throws(() => new core.Editor(profile, bytes, 'synthetic-invalid'));
  }
  const { bytes, profile } = baseSynthetic();
  assert.throws(() => new core.Editor(profile, bytes.subarray(0, bytes.length - 1), 'synthetic-short'));
  assert.throws(() => new core.Editor({ ...profile, codeSHA256: '0'.repeat(64) }, bytes, 'synthetic-wrong-profile'));
  new DataView(bytes.buffer).setFloat32(0x140100, Infinity, false);
  assert.throws(() => new core.Editor(profile, bytes, 'synthetic-nonfinite'), /não finito/);
});

test('projects reject wrong profiles, tampered source hashes and unauthorized patches', () => {
  const { bytes, profile } = baseSynthetic();
  const editor = new core.Editor(profile, bytes, 'synthetic-input');
  const project = JSON.parse(editor.project());
  assert.throws(() => core.Editor.fromProject({ ...profile, id: 'other-synthetic-profile' }, JSON.stringify(project)));
  assert.throws(() => core.Editor.fromProject(profile, JSON.stringify({ ...project, sourceSHA256: '0'.repeat(64) })));
  assert.throws(() => core.Editor.fromProject(profile, JSON.stringify({ ...project, patches: [{ address: 0x5000, value: 1 }] })));
});

test('fixed checksum metadata mismatch is rejected before accepting an image', () => {
  const { bytes } = baseSynthetic();
  bytes[0x15BD80] ^= 1;
  assert.throws(() => core.checkImage(bytes), /Metadados/);
  assert.throws(() => core.checkImage(new Uint8Array(4)), /2 MiB/);
});

test('public profile ships 228 well formed map definitions without loading a vehicle image', () => {
  const profile = require('../src/profile.json');
  assert.equal(profile.maps.length, 228);
  assert.equal(new Set(profile.maps.map(map => map.id)).size, profile.maps.length);
  for (const map of profile.maps) {
    assert.ok(Number.isInteger(map.nx) && map.nx > 0);
    assert.ok(Number.isInteger(map.ny) && map.ny > 0);
    assert.equal(map.addresses.length, map.nx * map.ny, map.id);
    for (const address of map.addresses) {
      assert.ok(Number.isInteger(address) && address >= 0 && address + 4 <= profile.bytes, map.id);
    }
  }
});
